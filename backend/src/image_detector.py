def decode_metadata_text(raw_bytes: bytes) -> str:
    if not raw_bytes:
        return ""
    if len(raw_bytes) > 2_500_000:
        raw_bytes = raw_bytes[:2_000_000] + raw_bytes[-500_000:]
    text_parts = []
    for encoding in ("utf-8", "utf-16-le"):
        try:
            text_parts.append(raw_bytes.decode(encoding, errors="ignore"))
        except Exception:
            pass
    try:
        return re.sub(
            r"[^\x09\x0a\x0d\x20-\x7E\u0600-\u06FF]+",
            " ",
            "\n".join(text_parts).replace("\x00", " "),
        ).lower()
    except Exception:
        return "\n".join(text_parts).replace("\x00", " ").lower()

def metadata_text_has_tag(raw_text: str, tag: str) -> bool:
    try:
        needle = tag.lower()
        if re.fullmatch(r"[a-z0-9-]+", needle):
            return re.search(rf"(^|[^a-z0-9]){re.escape(needle)}([^a-z0-9]|$)", raw_text) is not None
        return needle in raw_text
    except Exception:
        return tag.lower() in raw_text

class SoftwareMetadataAnalyzer(BaseDetector):
    def __init__(self):
        super().__init__("Software Metadata Analyzer", "1.0", "provenance")

    def preprocess(self, input_data: Any, context: dict) -> dict:
        # input_data is raw_bytes
        raw_text = decode_metadata_text(input_data)
        return {"raw_text": raw_text}

    def extract_features(self, preprocessed_data: dict, context: dict) -> dict:
        raw_text = preprocessed_data["raw_text"]
        if not raw_text:
            return {"failed": True, "reason": "No metadata text provided"}

        ai_tag = next((tag for tag in AI_SOFTWARE_TAGS if metadata_text_has_tag(raw_text, tag)), None)
        editor_tag = next((tag for tag in EDITOR_SOFTWARE_TAGS if metadata_text_has_tag(raw_text, tag)), None)
        
        if ai_tag in WEAK_AI_METADATA_TAGS and not any(tag in raw_text for tag in STRONG_AI_CONTEXT_TAGS):
            ai_tag = None
        
        return {
            "ai_tag_found": ai_tag,
            "editor_tag_found": editor_tag,
            "failed": False
        }

    def evaluate_signal_quality(self, features: dict, context: dict) -> float:
        if features.get("failed"):
            return 0.0
        if features.get("ai_tag_found") or features.get("editor_tag_found"):
            return 1.0
        return 0.1 # Missing metadata doesn't indicate human, it's just missing

    def predict_raw(self, features: dict, context: dict) -> float:
        if features.get("failed"):
            return 0.5
        
        if features["ai_tag_found"]:
            return 0.99
        if features["editor_tag_found"]:
            return 0.40 # Editors might indicate human drafting but can be used for AI too
            
        return 0.5

    def calibrate(self, raw_score: float, context: dict) -> float:
        return raw_score


class HardwareProvenanceAnalyzer(BaseDetector):
    def __init__(self):
        super().__init__("Hardware Provenance Analyzer", "1.0", "provenance")

    def preprocess(self, input_data: Any, context: dict) -> dict:
        raw_text = decode_metadata_text(input_data)
        return {"raw_text": raw_text}

    def extract_features(self, preprocessed_data: dict, context: dict) -> dict:
        raw_text = preprocessed_data["raw_text"]
        if not raw_text:
            return {"failed": True, "reason": "No metadata text provided"}

        camera_hint = next((tag for tag in CAMERA_HINT_TAGS if metadata_text_has_tag(raw_text, tag)), None)
        raw_capture_marker = next((tag for tag in RAW_CAPTURE_MARKERS if metadata_text_has_tag(raw_text, tag)), None)
        
        has_camera_workflow = bool(camera_hint and (raw_capture_marker or "exif" in raw_text))
        
        return {
            "camera_hint": camera_hint,
            "raw_capture_marker": raw_capture_marker,
            "has_camera_workflow": has_camera_workflow,
            "failed": False
        }

    def evaluate_signal_quality(self, features: dict, context: dict) -> float:
        if features.get("failed"):
            return 0.0
        if features.get("has_camera_workflow"):
            return 1.0
        if features.get("camera_hint"):
            return 0.5
        return 0.1

    def predict_raw(self, features: dict, context: dict) -> float:
        if features.get("failed"):
            return 0.5
            
        if features["has_camera_workflow"]:
            return 0.05 # Very strong hardware/sensor signal
        if features["camera_hint"]:
            return 0.25 # Weak hardware hint
            
        return 0.5

    def calibrate(self, raw_score: float, context: dict) -> float:
        return raw_score


class ImageProvenanceOrchestrator:
    def __init__(self):
        self.detectors = [
            SoftwareMetadataAnalyzer(),
            HardwareProvenanceAnalyzer()
        ]

    def analyze(self, raw_bytes: bytes, context: Optional[Dict[str, Any]] = None) -> List[DetectionSignal]:
        ctx = context or {}
        signals = []
        
        for det in self.detectors:
            try:
                signal = det.execute(raw_bytes, ctx)
                # Only keep signals with at least some quality, unless they are definitively 0.5 (neutral)
                if signal.signal_quality is not None and signal.signal_quality >= 0.1:
                    signals.append(signal)
            except Exception as e:
                print(f"Failed to execute {det.name}: {e}")
                
        return signals


